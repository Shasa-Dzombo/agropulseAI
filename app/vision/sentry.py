class SentryScheduler:
    """
    Automated scheduling system for Sentry operations.
    
    Manages periodic measurements, sleep cycles, and optimization
    for battery life.
    """
    
    def __init__(self, device: SentryDevice):
        """
        Initialize scheduler.
        
        Args:
            device: Sentry device to schedule
        """
        self.device = device
        self.schedule: List[Dict] = []
        self.running = False
        
    def add_measurement_schedule(
        self,
        interval_minutes: int,
        start_time: Optional[datetime] = None,
        end_time: Optional[datetime] = None
    ) -> None:
        """
        Add periodic measurement schedule.
        
        Args:
            interval_minutes: Measurement interval
            start_time: Schedule start time (None = now)
            end_time: Schedule end time (None = indefinite)
        """
        schedule = {
            'type': 'measurement',
            'interval_minutes': interval_minutes,
            'start_time': start_time or datetime.now(),
            'end_time': end_time,
            'last_run': None,
            'enabled': True
        }
        
        self.schedule.append(schedule)
        print(f"[Scheduler] Added measurement schedule: every {interval_minutes} minutes")
    
    def add_sleep_schedule(
        self,
        sleep_start_hour: int,
        sleep_end_hour: int
    ) -> None:
        """
        Add daily sleep schedule.
        
        Args:
            sleep_start_hour: Hour to enter sleep (0-23)
            sleep_end_hour: Hour to wake (0-23)
        """
        schedule = {
            'type': 'sleep',
            'sleep_start_hour': sleep_start_hour,
            'sleep_end_hour': sleep_end_hour,
            'enabled': True
        }
        
        self.schedule.append(schedule)
        print(f"[Scheduler] Added sleep schedule: {sleep_start_hour}:00 - {sleep_end_hour}:00")
    
    def run(self, duration_hours: Optional[float] = None) -> None:
        """
        Run scheduler.
        
        Args:
            duration_hours: Run duration (None = indefinite)
        """
        self.running = True
        start_time = datetime.now()
        
        print("[Scheduler] Starting scheduler...")
        
        try:
            while self.running:
                current_time = datetime.now()
                
                # Check if duration exceeded
                if duration_hours:
                    elapsed_hours = (current_time - start_time).total_seconds() / 3600
                    if elapsed_hours >= duration_hours:
                        break
                
                # Process schedules
                for schedule_item in self.schedule:
                    if not schedule_item['enabled']:
                        continue
                    
                    if schedule_item['type'] == 'measurement':
                        self._process_measurement_schedule(schedule_item, current_time)
                    elif schedule_item['type'] == 'sleep':
                        self._process_sleep_schedule(schedule_item, current_time)
                
                # Sleep briefly
                time.sleep(10)  # Check every 10 seconds
                
        except KeyboardInterrupt:
            print("[Scheduler] Interrupted by user")
        finally:
            self.running = False
            print("[Scheduler] Scheduler stopped")
    
    def stop(self) -> None:
        """Stop scheduler."""
        self.running = False
    
    def _process_measurement_schedule(
        self,
        schedule: Dict,
        current_time: datetime
    ) -> None:
        """Process measurement schedule item."""
        # Check if it's time to run
        if schedule['last_run'] is None:
            should_run = True
        else:
            elapsed = (current_time - schedule['last_run']).total_seconds() / 60
            should_run = elapsed >= schedule['interval_minutes']
        
        # Check time window
        if schedule['start_time'] and current_time < schedule['start_time']:
            should_run = False
        if schedule['end_time'] and current_time > schedule['end_time']:
            should_run = False
        
        if should_run:
            print(f"[Scheduler] Executing scheduled measurement")
            
            # Capture and process
            measurement = self.device.capture_multispectral()
            if measurement:
                self.device.process_measurement(measurement)
            
            schedule['last_run'] = current_time
    
    def _process_sleep_schedule(
        self,
        schedule: Dict,
        current_time: datetime
    ) -> None:
        """Process sleep schedule item."""
        current_hour = current_time.hour
        sleep_start = schedule['sleep_start_hour']
        sleep_end = schedule['sleep_end_hour']
        
        # Check if we're in sleep window
        if sleep_start < sleep_end:
            in_sleep_window = sleep_start <= current_hour < sleep_end
        else:  # Crosses midnight
            in_sleep_window = current_hour >= sleep_start or current_hour < sleep_end
        
        # Enter/exit sleep mode
        if in_sleep_window and self.device.status != DeviceStatus.IDLE:
            print(f"[Scheduler] Entering sleep mode")
            self.device.enter_sleep_mode()
        elif not in_sleep_window and self.device.status == DeviceStatus.IDLE:
            print(f"[Scheduler] Waking from sleep")
            self.device.wake_from_sleep()
