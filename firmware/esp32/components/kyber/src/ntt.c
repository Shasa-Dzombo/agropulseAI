/*************************************************
* Name:        ntt
*
* Description: Computes number-theoretic transform (NTT) of a polynomial in place;
*              inputs assumed to be in normal order, output in bitreversed order
*
* Arguments:   - int16_t *r: pointer to in/output polynomial
**************************************************/
void ntt(int16_t *r)
{
  unsigned int len, start, j, k;
  int16_t t, zeta;

  k = 1;
  for(len=128;len>=2;len>>=1)
  {
    for(start=0;start<256;start=j+len)
    {
      zeta = zetas[k++];
      for(j=start;j<start+len;j++)
      {
        t = montgomery_reduce((int32_t)zeta * r[j+len]);
        r[j+len] = r[j] - t;
        r[j] = r[j] + t;
      }
    }
  }
}


/*************************************************
* Name:        invntt
*
* Description: Computes inverse of number-theoretic transform (NTT) of a polynomial in place;
*              inputs assumed to be in bitreversed order, output in normal order
*
* Arguments:   - int16_t *a: pointer to in/output polynomial
**************************************************/
void invntt(int16_t *r)
{
  unsigned int start, len, j, k;
  int16_t t, zeta;
  const int16_t f = 1441; // mont^2/128

  k = 127;
  for(len=2;len<=128;len<<=1)
  {
    for(start=0;start<256;start=j+len)
    {
      zeta = zetas[k--];
      for(j=start;j<start+len;j++)
      {
        t = r[j];
        r[j] = barrett_reduce(t + r[j+len]);
        r[j+len] = r[j+len] - t;
        r[j+len] = montgomery_reduce((int32_t)zeta * r[j+len]);
      }
    }
  }

  for(j=0;j<256;j++)
    r[j] = montgomery_reduce((int32_t)f * r[j]);
}
