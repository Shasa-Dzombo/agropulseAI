class SentryDevice:
    """
    Low-cost CCTV-based Sentry Stake device controller.
    
    Manages camera, LEDs, processing, and communication for automated
    plant health monitoring.
    """
    
    def __init__(
        self,
        device_id: str,
        config: Optional[SentryConfig] = None
    ):
        """
        Initialize Sentry device.
        
        Args:
            device_id: Unique device identifier
            config: Device configuration
        """
        self.device_id = device_id
        self.config = config or SentryConfig(
            device_id=device_id,
            firmware_version="1.0.0"
        )
        
        self.status = DeviceStatus.OFFLINE
        self.battery_level = 100.0
        self.last_measurement: Optional[SentryMeasurement] = None
        
        # Initialize components
        self.camera = self._initialize_camera()
        self.led_controller = LEDController(
            nir_power=config.nir_led_power if config else 100,
            red_power=config.red_led_power if config else 100
        )
        self.edge_processor = EdgeAIProcessor()
        
        # Measurement history
        self.measurement_history: List[SentryMeasurement] = []
        self.alert_queue: List[SentryAlert] = []
        
    def _initialize_camera(self) -> Dict:
        """Initialize camera interface."""
        return {
            'resolution': self.config.resolution,
            'frame_rate': self.config.frame_rate,
            'initialized': True,
            'last_capture': None
        }
    
    def start(self) -> bool:
        """Start Sentry device operation."""
        try:
            # Power on components
            self._power_on_camera()
            self.led_controller.initialize()
            
            # Set status
            self.status = DeviceStatus.IDLE
            
            print(f"[{self.device_id}] Sentry device started successfully")
            return True
            
        except Exception as e:
            print(f"[{self.device_id}] Error starting device: {e}")
            self.status = DeviceStatus.ERROR
            return False
    
    def stop(self) -> bool:
        """Stop Sentry device operation."""
        try:
            # Power off components
            self._power_off_camera()
            self.led_controller.shutdown()
            
            # Set status
            self.status = DeviceStatus.OFFLINE
            
            print(f"[{self.device_id}] Sentry device stopped")
            return True
            
        except Exception as e:
            print(f"[{self.device_id}] Error stopping device: {e}")
            return False
    
    def capture_multispectral(self) -> SentryMeasurement:
        """
        Capture multispectral images with LED illumination.
        
        Returns:
            SentryMeasurement with captured data
        """
        self.status = DeviceStatus.CAPTURING
        
        try:
            # Capture ambient image (no LED)
            ambient_image = self._capture_frame()
            
            # Capture with NIR LED
            self.led_controller.activate_nir()
            time.sleep(0.1)  # Allow LED to stabilize
            nir_image = self._capture_frame()
            self.led_controller.deactivate_nir()
            
            # Small delay between captures
            time.sleep(0.05)
            
            # Capture with Red LED
            self.led_controller.activate_red()
            time.sleep(0.1)
            red_image = self._capture_frame()
            self.led_controller.deactivate_red()
            
            # Create measurement
            measurement = SentryMeasurement(
                timestamp=datetime.now(),
                device_id=self.device_id,
                nir_image=nir_image,
                red_image=red_image,
                ambient_image=ambient_image,
                battery_level=self.battery_level
            )
            
            self.status = DeviceStatus.IDLE
            return measurement
            
        except Exception as e:
            print(f"[{self.device_id}] Error capturing: {e}")
            self.status = DeviceStatus.ERROR
            return None
    
    def process_measurement(
        self,
        measurement: SentryMeasurement
    ) -> SentryMeasurement:
        """
        Process captured measurement on edge device.
        
        Args:
            measurement: Raw measurement data
            
        Returns:
            Processed measurement with NDVI and stress analysis
        """
        self.status = DeviceStatus.PROCESSING
        
        try:
            # Extract spectral channels
            nir_channel = self._extract_channel(
                measurement.nir_image,
                measurement.ambient_image,
                'nir'
            )
            red_channel = self._extract_channel(
                measurement.red_image,
                measurement.ambient_image,
                'red'
            )
            
            # Calculate NDVI on edge
            if self.config.ndvi_calculation_enabled:
                ndvi_result = self.edge_processor.calculate_ndvi(
                    nir_channel,
                    red_channel
                )
                measurement.ndvi_mean = ndvi_result['mean']
                measurement.ndvi_map = ndvi_result['map']
            
            # Detect stress on edge
            if self.config.stress_detection_enabled:
                stress_result = self.edge_processor.detect_stress(
                    ndvi_result['map'] if ndvi_result else None
                )
                measurement.stress_level = stress_result['level']
                measurement.stress_map = stress_result['map']
            
            # Check for alert conditions
            self._check_alert_conditions(measurement)
            
            # Store measurement
            self.last_measurement = measurement
            self.measurement_history.append(measurement)
            
            # Trim history if needed
            if len(self.measurement_history) > 1000:
                self.measurement_history = self.measurement_history[-1000:]
            
            self.status = DeviceStatus.IDLE
            return measurement
            
        except Exception as e:
            print(f"[{self.device_id}] Error processing: {e}")
            self.status = DeviceStatus.ERROR
            return measurement
    
    def _extract_channel(
        self,
        illuminated: Optional[np.ndarray],
        ambient: Optional[np.ndarray],
        channel: str
    ) -> np.ndarray:
        """Extract spectral channel from illuminated image."""
        if illuminated is None:
            return np.zeros((480, 640), dtype=np.float32)
        
        # Convert to grayscale if needed
        if len(illuminated.shape) == 3:
            if channel == 'nir' or channel == 'red':
                gray = illuminated[:, :, 2].astype(np.float32)  # Red channel
            else:
                gray = np.mean(illuminated, axis=2).astype(np.float32)
        else:
            gray = illuminated.astype(np.float32)
        
        # Subtract ambient if available
        if ambient is not None:
            if len(ambient.shape) == 3:
                ambient_gray = np.mean(ambient, axis=2).astype(np.float32)
            else:
                ambient_gray = ambient.astype(np.float32)
            
            gray = np.maximum(gray - ambient_gray * 0.3, 0)
        
        # Normalize
        gray = gray / 255.0
        
        return gray
    
    def _check_alert_conditions(self, measurement: SentryMeasurement) -> None:
        """Check if measurement triggers any alerts."""
        alerts = []
        
        # NDVI alert
        if (measurement.ndvi_mean is not None and
            measurement.ndvi_mean < self.config.alert_threshold_ndvi):
            alert = SentryAlert(
                alert_id=f"{self.device_id}_{datetime.now().timestamp()}",
                timestamp=datetime.now(),
                device_id=self.device_id,
                alert_type="low_ndvi",
                severity="high" if measurement.ndvi_mean < 0.3 else "medium",
                message=f"Low NDVI detected: {measurement.ndvi_mean:.2f}",
                ndvi_value=measurement.ndvi_mean
            )
            alerts.append(alert)
        
        # Stress alert
        if measurement.stress_level > self.config.alert_threshold_stress:
            alert = SentryAlert(
                alert_id=f"{self.device_id}_{datetime.now().timestamp()}",
                timestamp=datetime.now(),
                device_id=self.device_id,
                alert_type="high_stress",
                severity="critical" if measurement.stress_level > 0.85 else "high",
                message=f"High stress detected: {measurement.stress_level*100:.0f}%",
                stress_level=measurement.stress_level
            )
            alerts.append(alert)
        
        # Battery alert
        if measurement.battery_level < self.config.low_power_threshold:
            alert = SentryAlert(
                alert_id=f"{self.device_id}_{datetime.now().timestamp()}",
                timestamp=datetime.now(),
                device_id=self.device_id,
                alert_type="low_battery",
                severity="medium",
                message=f"Low battery: {measurement.battery_level:.0f}%"
            )
            alerts.append(alert)
        
        # Add to alert queue
        self.alert_queue.extend(alerts)
    
    def get_pending_alerts(self) -> List[SentryAlert]:
        """Get all pending unacknowledged alerts."""
        return [a for a in self.alert_queue if not a.acknowledged]
    
    def acknowledge_alert(self, alert_id: str) -> bool:
        """Acknowledge an alert."""
        for alert in self.alert_queue:
            if alert.alert_id == alert_id:
                alert.acknowledged = True
                return True
        return False
    
    def enter_sleep_mode(self) -> None:
        """Enter low-power sleep mode."""
        if self.config.sleep_mode_enabled:
            self._power_off_camera()
            self.led_controller.shutdown()
            self.status = DeviceStatus.IDLE
            print(f"[{self.device_id}] Entering sleep mode")
    
    def wake_from_sleep(self) -> None:
        """Wake from sleep mode."""
        self._power_on_camera()
        self.led_controller.initialize()
        self.status = DeviceStatus.IDLE
        print(f"[{self.device_id}] Waking from sleep")
    
    def _capture_frame(self) -> np.ndarray:
        """Capture single frame from camera."""
        # Placeholder: would interface with actual camera
        # Simulate capture
        h, w = self.config.resolution[1], self.config.resolution[0]
        frame = np.random.randint(0, 256, (h, w, 3), dtype=np.uint8)
        return frame
    
    def _power_on_camera(self) -> None:
        """Power on camera."""
        self.camera['initialized'] = True
    
    def _power_off_camera(self) -> None:
        """Power off camera."""
        self.camera['initialized'] = False
    
    def get_status(self) -> Dict:
        """Get device status summary."""
        return {
            'device_id': self.device_id,
            'status': self.status.value,
            'firmware_version': self.config.firmware_version,
            'battery_level': self.battery_level,
            'last_measurement': self.last_measurement.timestamp if self.last_measurement else None,
            'pending_alerts': len(self.get_pending_alerts()),
            'measurements_stored': len(self.measurement_history)
        }


